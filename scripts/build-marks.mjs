// Converts src/img/marks/*.svg into src/js/marks.js so tiles can draw them inline with any color.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'src');
const dir = join(root, 'img', 'marks');
const marks = {};

for (const file of readdirSync(dir).filter(f => f.endsWith('.svg')).sort()) {
    const svg = readFileSync(join(dir, file), 'utf8');
    const viewBox = (svg.match(/viewBox="([^"]+)"/) || [])[1] || '0 0 24 24';
    const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map(m => m[1]);
    if (paths.length) marks[file.replace('.svg', '')] = { viewBox, d: paths.join(' ') };
}

writeFileSync(join(root, 'js', 'marks.js'),
    '/* Generated by scripts/build-marks.mjs. Simple Icons (CC0) and Custom Brand Icons (MIT). */\n' +
    'window.MARKS = ' + JSON.stringify(marks, null, 1) + ';\n');
console.log('marks:', Object.keys(marks).join(', '));
